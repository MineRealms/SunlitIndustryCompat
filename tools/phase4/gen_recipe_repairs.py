"""Explicit, reviewable hot-reload repairs generated from the full server recipe dump."""
from pathlib import Path
import json
import copy
import collections

REPORT=Path('G:/emoney-full-phase4-20261104/phase4-reports')
PACK=Path('G:/MinecraftGames/Sunlit Valley(BaopuEdition)/.minecraft/versions/Society Sunlit Valley')
full=json.loads((REPORT/'target-recipes.json').read_text())
recipes=json.loads((REPORT/'repair-data.json').read_text())['recipes']
aspects=full['aspects']
remove=set()
replace={}
notes=[]

def circuit(recipe, n):
    r=copy.deepcopy(recipe)
    items=r.setdefault('inputs',{}).setdefault('item',[])
    for x in items:
        if x['content'].get('type')=='gtceu:circuit':
            x['content']['configuration']=n
            return r
    items.append({'content':{'type':'gtceu:circuit','configuration':n},'chance':0})
    return r

# Every compound is 1000mB + 1000mB -> 1000mB, following TC4R's current graph.
# Fames has no Pollution fluid: inline victus + vacuos, rather than inventing a cheap substitute.
for aspect, meta in aspects.items():
    components=meta['components']
    if not components: continue
    inputs=[]
    for c in components:
        parts=[c] if c in aspects else (['thaumcraft:victus','thaumcraft:vacuos'] if c=='thaumcraft:fames' else None)
        if parts is None: raise ValueError('unmapped aspect '+c)
        inputs.extend(parts)
    id='pollution:mixer/compound_aspect/compound/'+meta['material']
    old=recipes[id]
    r=copy.deepcopy(old)
    r['inputs']={'fluid':[{'content':{'amount':1000*count,'value':[{'fluid':aspects[c]['fluid']}]}} for c,count in collections.Counter(inputs).items()]}
    r['outputs']={'fluid':[{'content':{'amount':1000,'value':[{'fluid':meta['fluid']}]}}]}
    replace[id]=r
notes.append('30 TC4R-mapped compounds: graph-correct inputs, 1000mB output; fames expanded into victus+vacuos.')
remove.add('pollution:magic_chemical_reactor/magic_chemical/paradox_matter')
notes.append('Remove legacy 120EU/t alumentum -> primordial pearl placeholder; retain gated industrial synthesis.')

# Empty shell recipes are remnants of disabled chemistry, not alternative production routes.
for id,r in recipes.items():
    if id.startswith('gtceu:') and not r.get('inputs') and not r.get('outputs') and not r.get('tickOutputs'):
        remove.add(id)

# One entry is a misnamed duplicate; keep the accurately named product recipe.
for typ in ['chemical_reactor','large_chemical_reactor']:
    remove.add('gcyr:'+typ+'/potassium_hydroxide')
    for suffix in ['platinum_group_sludge_tiny_dust1','platinum_group_sludge_tiny_dust2']:
        remove.add('gtceu:'+typ+'/'+suffix)
remove.add('gtceu:bender/dense_lanthanum')
remove.add('gtceu:extractor/potassium_pyrosulfate_dust')

# Distinct products retain both routes with circuit selection; all other inputs/outputs unchanged.
for id,n in {
 'gtceu:alloy_blast_smelter/mar_m_200':8,
 'gtceu:distillery/distill_coal_tar_to_durene':6,
 'gtceu:extractor/extract_monazite_dust':1,
 'gtceu:extractor/extract_quartzite_dust':1,
 'gtceu:large_chemical_reactor/raw_palladium_separation_large':2,
}.items():
    replace[id]=circuit(recipes[id],n)

# GT lookup keys ignore amounts. A 1x dual hatch and a 16x dual hatch share input item IDs,
# despite different quantities; use a circuit to select capacity instead of dropping either recipe.
for id,r in recipes.items():
    if not id.startswith('gtmadvancedhatch:assembler/') or 'configurable' not in id:continue
    n=1
    for suffix,value in [('_4_x',4),('_8_x',8),('_16_x',16),('_16_p',16)]:
        if id.endswith(suffix):n=value
    replace[id]=circuit(r,n)

remove.update(replace)
lines=['// priority: -1000','// Full-server audited phase-4 corrections; generated by SunlitIndustryCompat/tools/phase4/gen_recipe_repairs.py.',
       '// Explicit IDs only. Existing inputs, EU/t and durations are preserved except documented aspect conservation.',
       'ServerEvents.recipes((event) => {','  if (!Platform.isLoaded("gtceu")) return;']
for id in sorted(remove):lines.append('  event.remove({id: '+json.dumps(id)+'});')
for id,r in sorted(replace.items()):
    ns=id.split(':',1)[0]
    guard='Platform.isLoaded('+json.dumps(ns)+')'
    # GT 的 event.custom 返回的是已注册的 GTRecipe 实例，没有 .id() 方法；
    # 链式调用会在第一条就抛 TypeError，导致后面所有替换被跳过。
    # 目标 id 已在上面的 event.remove 里释放，这里只负责把修正后的配方重新注册。
    lines.append('  // was: '+id)
    lines.append('  if ('+guard+') event.custom('+json.dumps(r,separators=(',',':'))+');')
lines.append('  console.info("[PHASE4-RECIPES] explicit conservation/conflict repairs installed");')
lines.append('});')
out=PACK/'kubejs/server_scripts/gt/phase4RecipeRepairs.js'
out.write_text('\n'.join(lines)+'\n',encoding='utf-8')
(REPORT/'recipe-repair-manifest.json').write_text(json.dumps({'removed':sorted(remove-replace.keys()),'replaced':sorted(replace),'notes':notes},indent=2),encoding='utf-8')
print('removed',len(remove-replace.keys()),'replaced',len(replace),'file',out)
